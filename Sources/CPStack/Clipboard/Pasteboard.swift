import AppKit
import CryptoKit

/// A snapshot of the general pasteboard taken right after it changed.
nonisolated struct RawClip: Sendable {
    enum Content: Sendable {
        case text(plain: String, payload: PasteboardPayload, isRich: Bool)
        case image(data: Data, isPNG: Bool)
        case files([URL])
    }

    var content: Content
    var date: Date
    var source: SourceApp?

    var contentHash: String {
        var hasher = SHA256()
        switch content {
        case .text(let plain, _, _):
            hasher.update(data: Data("text:".utf8))
            hasher.update(data: Data(plain.utf8))
        case .image(let data, _):
            hasher.update(data: Data("image:".utf8))
            hasher.update(data: data)
        case .files(let urls):
            hasher.update(data: Data("files:".utf8))
            hasher.update(data: Data(urls.map(\.path).joined(separator: "\n").utf8))
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

enum Pasteboard {
    /// Types marked by password managers and other apps as private or temporary.
    /// See http://nspasteboard.org
    static let confidentialTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.typeit4me.clipping"),
        .init("Pasteboard generator type"),
    ]

    /// Text representations worth keeping to paste rich text back faithfully.
    static let textTypes: [NSPasteboard.PasteboardType] = [.string, .rtf, .rtfd, .html, .URL]
    static let richTextTypes: Set<NSPasteboard.PasteboardType> = [.rtf, .rtfd, .html]

    /// Payloads larger than this are skipped to keep the history light.
    static let maxPayloadSize = 50 * 1024 * 1024

    static func read(_ pasteboard: NSPasteboard, ignoreConfidential: Bool, includeImages: Bool) -> RawClip.Content? {
        guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return nil }
        let types = Set(items.flatMap(\.types))
        if ignoreConfidential, !types.isDisjoint(with: confidentialTypes) { return nil }

        let fileURLs = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL] ?? []
        if !fileURLs.isEmpty {
            return .files(fileURLs)
        }

        let plain = pasteboard.string(forType: .string) ?? ""
        let hasText = !plain.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        let isRich = !types.isDisjoint(with: richTextTypes)
        let imageType: NSPasteboard.PasteboardType? = types.contains(.png) ? .png : (types.contains(.tiff) ? .tiff : nil)

        // An image wins over text only when the text is just a by-product,
        // e.g. the URL that Safari adds next to a copied picture.
        if let imageType, !hasText || !isRich {
            guard includeImages else { return hasText ? textContent(items, plain: plain, isRich: isRich) : nil }
            guard let data = pasteboard.data(forType: imageType), data.count <= maxPayloadSize else { return nil }
            return .image(data: data, isPNG: imageType == .png)
        }

        guard hasText else { return nil }
        return textContent(items, plain: plain, isRich: isRich)
    }

    private static func textContent(_ items: [NSPasteboardItem], plain: String, isRich: Bool) -> RawClip.Content? {
        var total = 0
        var payload: PasteboardPayload = []
        for item in items {
            var representations: [String: Data] = [:]
            for type in textTypes where item.types.contains(type) {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                representations[type.rawValue] = data
            }
            if !representations.isEmpty { payload.append(representations) }
        }
        guard total <= maxPayloadSize else { return nil }
        return .text(plain: plain, payload: payload, isRich: isRich)
    }

    /// Puts a history item back on the general pasteboard.
    static func write(_ item: ClipItem, plainText: Bool, storage: HistoryStorage, to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()

        switch item.kind {
        case .text:
            let payload = storage.readPayload(for: item.id) ?? []
            if plainText || payload.isEmpty {
                let plain = payload.first?[NSPasteboard.PasteboardType.string.rawValue]
                    .flatMap { String(data: $0, encoding: .utf8) } ?? item.preview
                pasteboard.setString(plain, forType: .string)
            } else {
                let items = payload.map { representations in
                    let item = NSPasteboardItem()
                    for (type, data) in representations {
                        item.setData(data, forType: .init(type))
                    }
                    return item
                }
                pasteboard.writeObjects(items)
            }

        case .image:
            guard let png = storage.readImage(for: item.id) else { return }
            let pbItem = NSPasteboardItem()
            pbItem.setData(png, forType: .png)
            if let tiff = NSImage(data: png)?.tiffRepresentation {
                pbItem.setData(tiff, forType: .tiff)
            }
            pasteboard.writeObjects([pbItem])

        case .files:
            if plainText {
                pasteboard.setString(item.fileURLs.map(\.path).joined(separator: "\n"), forType: .string)
            } else {
                pasteboard.writeObjects(item.fileURLs as [NSURL])
            }
        }
    }
}
